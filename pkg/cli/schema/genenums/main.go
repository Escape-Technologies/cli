// Command genenums writes enums.go from the generated client's Allowed*EnumValues
// slices. Go reflection cannot list package variables, so the schema package
// registers each slice by name. Re-run from pkg/cli/schema with go generate.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var allowedEnum = regexp.MustCompile(`var\s+(Allowed[A-Za-z0-9]+EnumValues)\s*=`)

// generatedEnumFileMode is the mode of the generated enums.go.
const generatedEnumFileMode os.FileMode = 0o644

func main() {
	v3Dir := filepath.Clean(filepath.Join("..", "..", "api", "v3"))
	names := map[string]struct{}{}
	err := filepath.WalkDir(v3Dir, func(path string, entry os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}

		if entry.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}

		body, readErr := os.ReadFile(path)
		if readErr != nil {
			return fmt.Errorf("read %s: %w", path, readErr)
		}

		for _, match := range allowedEnum.FindAllSubmatch(body, -1) {
			names[string(match[1])] = struct{}{}
		}

		return nil
	})
	if err != nil {
		fmt.Fprintf(os.Stderr, "scan v3 enums: %v\n", err)
		os.Exit(1)
	}

	if len(names) == 0 {
		fmt.Fprintln(os.Stderr, "found no Allowed*EnumValues slices")
		os.Exit(1)
	}

	ordered := make([]string, 0, len(names))
	for name := range names {
		ordered = append(ordered, name)
	}

	sort.Strings(ordered)

	var buf bytes.Buffer
	buf.WriteString(`// Code generated by go generate. DO NOT EDIT.
//
// The generated client exposes each enum as a named string type plus a
// package-level Allowed<Type>EnumValues slice. Reflection cannot list
// package variables, so this file names every slice. Adding a generated
// enum without re-running go generate fails TestGeneratedEnumListsAreRegistered.

package schema

import (
	v3 "github.com/Escape-Technologies/cli/pkg/api/v3"
)

func init() {
	registerEnumLists(
`)
	for _, name := range ordered {
		fmt.Fprintf(&buf, "\t\tv3.%s,\n", name)
	}

	buf.WriteString("\t)\n}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintf(os.Stderr, "format enums.go: %v\n", err)
		os.Exit(1)
	}

	if err := os.WriteFile("enums.go", formatted, generatedEnumFileMode); err != nil {
		fmt.Fprintf(os.Stderr, "write enums.go: %v\n", err)
		os.Exit(1)
	}
}
